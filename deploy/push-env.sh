#!/usr/bin/env bash
#
# Compose /etc/yohaku/env on the host from the secrets already on this workstation.
#
#   DOMAIN=yohaku.texx.io HOST=ubuntu@161.33.129.124 bash push-env.sh
#   DRY_RUN=1 DOMAIN=yohaku.texx.io bash push-env.sh      # print it, values masked
#
# This REPLACES the file rather than appending, so the workstation `.env` is the single
# source of truth — anything added by hand on the host is lost on the next run. Put new
# secrets in `.env` (0600, gitignored), not in the remote file.
#
set -euo pipefail

DOMAIN="${DOMAIN:?set DOMAIN, e.g. DOMAIN=yohaku.texx.io}"
HOST="${HOST:-}"
DRY_RUN="${DRY_RUN:-}"
REPO_DIR="${REPO_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
SRC="$REPO_DIR/.env"

[ -f "$SRC" ] || { echo "no $SRC" >&2; exit 1; }
[ -n "$DRY_RUN" ] || [ -n "$HOST" ] || { echo "set HOST, e.g. HOST=ubuntu@161.33.129.124" >&2; exit 1; }

take() { grep -m1 "^$1=" "$SRC" || echo "# $1 is not in the workstation .env"; }

sink() {
  if [ -n "$DRY_RUN" ]; then
    sed -E 's/^([A-Z_][A-Z0-9_]*)=.+/\1=<set>/'
  else
    ssh "$HOST" 'sudo install -d -o root -g root -m 0700 /etc/yohaku \
      && sudo install -m 0600 /dev/null /etc/yohaku/env \
      && sudo tee /etc/yohaku/env >/dev/null \
      && sudo systemctl restart yohaku'
  fi
}

{
  echo "# Generated by push-env.sh. Values here win over the checkout's .env (src/core/env.ts:19)."
  echo "PORT=8402"
  echo
  echo "# Persistent state. Losing these loses the cross-restart idempotency that"
  echo "# src/server/state.ts relies on to keep a retry from settling twice."
  echo "REQUEST_STATE_FILE=/var/lib/yohaku/requests.json"
  echo "ATTENTION_STATE_FILE=/var/lib/yohaku/attention.json"
  echo
  echo "# The agent workspace and the phone web app."
  echo "YOHAKU_EXPERIENCE_ENABLED=true"
  echo
  echo "# World IDKit — the 'local' app in config/world-idkit.json, whose registered"
  echo "# signerAddress matches the key below. config/world-idkit-public.json belongs to"
  echo "# the Studio deployment and its key is not on this workstation."
  echo "WORLD_IDKIT_DEMO_ENABLED=true"
  echo "WORLD_IDKIT_DEPLOYMENT=local"
  echo "WORLD_IDKIT_ORIGIN=https://${DOMAIN}"
  take WORLD_IDKIT_SIGNING_KEY
  echo
  echo "# Rule 9 against the decision model. jevFromEnv returns undefined unless all three"
  echo "# are present, which would silently leave the classifier on the mock."
  take YOHAKU_PROVIDER
  take JEV_API_KEY
  take JEV_BASE_URL
  take JEV_MODEL
  echo
  echo "# Rule 4 against the real API."
  take INTERCEPTA_API_KEY
  take INTERCEPTA_BASE_URL
  take INTERCEPTA_SCAN_PATH
  take INTERCEPTA_AUTH_HEADER
  echo
  echo "# ENS delegation reader. OWNER_WALLET_ADDRESS is deliberately unset: with these"
  echo "# three matching config/ens-deployment.json, owner-config.ts:14 resolves the owner."
  take SEPOLIA_RPC_URL
  take ENS_NAME
  take ENS_RESOLVER_ADDRESS
  take ENS_DELEGATE_ADDRESS
  echo
  echo "# --- still on Kou's Mac Studio, intentionally absent here ---"
  echo "# Settlement. Without AGENT_PRIVATE_KEY this host cannot sign, which is why it is"
  echo "# safe to run alongside Studio (docs/build/HOSTING-MIGRATION.md:90). The buyer wallet"
  echo "# for this host is 0x9b264Cf3F8f8B3616F20c257058914B8e68d9Bd6; its key is held at"
  echo "# ~/.yohaku/buyer-key-yohaku-texx-io on the workstation, unfunded until kou sends USDC."
  echo "# AGENT_PRIVATE_KEY="
  echo "# X402_FACILITATOR_URL="
  echo "# X402_NETWORK="
  echo "# X402_ASSET="
  echo "# X402_PAYOUT_ADDRESS="
  echo "# X402_ASSET_NAME="
  echo "# X402_ASSET_VERSION="
  echo "# X402_ATOMIC_PER_UNIT="
  echo "# X402_EXPLORER_URL="
  echo "# DEMO_SIGNS_PER_HOUR="
} | sink

[ -n "$DRY_RUN" ] && exit 0

echo "pushed. checking:"
ssh "$HOST" 'sudo systemctl --no-pager --lines=8 status yohaku || true'
